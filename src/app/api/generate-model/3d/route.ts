/**
 * POST /api/generate-model/3d
 *
 * Tripo3D v2.5 — image-to-3D reconstruction.  Caller passes the clean FLUX
 * source image URL from /api/generate-model and gets back a textured GLB.
 *
 * All fal.ai transport + the in-memory cache lives in
 * `src/lib/imagegen/banana.ts`.  This route is a thin auth gate + logger.
 *
 * Caching: keyed by source imageUrl.  Two students viewing the same lesson
 * on the same Vercel Fluid Compute instance share a single Tripo3D call.
 * Since T06 the cache is durable (Supabase Storage), so the first student to
 * view a concept pays the $0.30 once and every student after inherits it —
 * which is what makes a model at this price affordable at all.
 */

import { NextRequest, NextResponse } from "next/server";
import { requireEntitlement, spendAllowance, releaseConsumed, type Consumed } from "@/lib/billing/entitlements";
import { generate3dModel }           from "@/lib/imagegen/banana";
import { blockedResponse, spendHook } from "@/lib/guard";
import { verifyAssetUrl }            from "@/lib/guard/assets";
import { conceptIdSchema, parseJsonBody } from "@/lib/guard/input";
import { createServiceClient }       from "@/lib/supabase/server";
import { z }                         from "zod";

// Tripo3D conversion alone runs 30-40s; with queue time a 60s cap produced
// intermittent 504s that the client used to swallow silently.  Vercel's
// platform limit is 300s on all plans — use it.
export const maxDuration = 300;

const BodySchema = z.object({
  imageUrl:       z.string().min(1).max(2048),
  conceptId:      conceptIdSchema.nullish(),
  needsMultiview: z.boolean().optional(),
}).strict();

export async function POST(req: NextRequest) {
  let consumed: Consumed | null = null;
  try {
    const guard = await requireEntitlement();
    if (guard.error) return guard.error;
    const { user } = guard;

    if (!process.env.FAL_KEY) {
      return NextResponse.json({ error: "FAL_KEY not configured" }, { status: 500 });
    }

    const parsed = await parseJsonBody(req, BodySchema);
    if (!parsed.ok) return parsed.response;
    const { conceptId, needsMultiview } = parsed.data;
    const resolvedConceptId: string | null = conceptId ?? null;

    // Only an image this app produced, and without its query string: `?n=1`, `?n=2` must not force a paid miss.
    const imageUrl = await verifyAssetUrl(parsed.data.imageUrl, createServiceClient());
    if (!imageUrl) {
      return NextResponse.json({ error: "imageUrl must be an image generated by this app" }, { status: 400 });
    }

    // The cache check lives inside generate3dModel, so count first and give the unit back on a cached result.
    const spent = await spendAllowance(guard.entitlement, "models_3d");
    if (spent.error) return spent.error;
    consumed = spent.consumed;

    const { modelUrl, cached } = await generate3dModel(imageUrl, user.id, false, resolvedConceptId, {
      multiview: needsMultiview === true,
      // Counted on a miss only: a cached model costs nothing and is never limited.
      beforeGenerate: spendHook(user.id, "generate_3d"),
    });
    if (cached) {
      await releaseConsumed(consumed);
      consumed = null;
    }

    return NextResponse.json({ modelUrl, cached });
  } catch (error) {
    await releaseConsumed(consumed);
    const refused = blockedResponse(error);
    if (refused) return refused;
    console.error("[generate-model/3d] error:", error);
    return NextResponse.json(
      { error: error instanceof Error ? error.message : "3D generation failed" },
      { status: 500 }
    );
  }
}
