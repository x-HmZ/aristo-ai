// V8.3c: the Column mark's outline as ordered points, for the opening (src/components/landing/intro/markPoints.ts).
// Sampled once here in a browser (getPointAtLength walks the path from its start on every call: 16k calls at run time
// took 6 s, 1.4k still 0.5 s), so the opening reads a constant.
const fs = require("fs");
const path = require("path");
const { chromium, LAUNCH } = require("../../2026-09-30-desk-framing/scripts/common.cjs");
const src = fs.readFileSync(path.join(__dirname, "..", "..", "..", "..", "src", "components", "brand", "markPaths.ts"), "utf8");
const block = src.slice(src.indexOf("export const COLUMN = {"));
const pick = (k) => block.match(new RegExp(`${k}: "([^"]+)"`))[1];
const COLUMN = { viewBox: pick("viewBox"), ink: pick("ink"), lit: pick("lit") };
(async () => {
  const b = await chromium.launch(LAUNCH);
  const p = await b.newPage();
  const pts = await p.evaluate(({ ink, lit }) => {
    const NS = "http://www.w3.org/2000/svg";
    const svg = document.createElementNS(NS, "svg");
    const make = (d) => { const e = document.createElementNS(NS, "path"); e.setAttribute("d", d); svg.appendChild(e); return e; };
    document.body.appendChild(svg);
    const a = make(ink), l = make(lit);
    const sample = (e, k) => { const len = e.getTotalLength(); return Array.from({ length: k }, (_, i) => { const q = e.getPointAtLength((i / (k - 1)) * len); return [Math.round(q.x * 10) / 10, Math.round(q.y * 10) / 10]; }); };
    return { ink: sample(a, 900), lit: sample(l, 260) };
  }, COLUMN);
  const out = path.join(__dirname, "..", "..", "..", "..", "src", "components", "landing", "intro", "markPoints.ts");
  fs.writeFileSync(out, `// Generated by .claude/eval/2026-10-03-v8-3c-landing/scripts/mark-points.cjs from markPaths.ts COLUMN. Do not edit by
// hand. The Column mark's outline in drawing order (viewBox units, ${COLUMN.viewBox}): the ink, then the lit flute.
export const MARK_VIEWBOX = "${COLUMN.viewBox}";
export const MARK_INK = new Float32Array([${pts.ink.flat().join(",")}]);
export const MARK_LIT = new Float32Array([${pts.lit.flat().join(",")}]);
`);
  console.log(out, fs.statSync(out).size, "bytes");
  await b.close();
})();
