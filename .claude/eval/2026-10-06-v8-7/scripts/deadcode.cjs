// V8.7 step 4: which --aristo-* tokens, BRAND_HEX keys, Tailwind aristo utilities and files are referenced
// outside their own definitions. Writes dead-code.md (the list Hmz confirms) and prints a summary.
//   node .claude/eval/2026-10-06-v8-7/scripts/deadcode.cjs
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..", "..", "..", "..");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const files = [];
const walk = (d) => { for (const f of fs.readdirSync(path.join(ROOT, d))) { const rel = path.join(d, f).split(path.sep).join("/"); const st = fs.statSync(path.join(ROOT, rel)); if (st.isDirectory()) { if (!["node_modules", ".next", "hx"].includes(f)) walk(rel); } else if (/\.(tsx?|jsx?|css|mjs|cjs)$/.test(f)) files.push(rel); } };
["src", "pages", "scripts"].forEach(walk);
files.push("tailwind.config.js");
const DEFS = new Set(["tailwind.config.js", "src/lib/brandColors.ts", "src/lib/brandColors.test.ts"]);

const css = read("src/app/globals.css");
const tokens = [...css.matchAll(/^\s*--aristo-([a-z-]+):/gm)].map((m) => m[1]);
const camel = (k) => k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const brand = read("src/lib/brandColors.ts");
const keys = [...brand.matchAll(/^\s{2}([a-zA-Z]+):\s*"#/gm)].map((m) => m[1]);

const isComment = (line) => /^\s*(\/\/|\*|\/\*|\{\/\*)/.test(line) || /\/\*.*\*\/\s*$/.test(line.trim()) && !/className|style|hsl\(/.test(line);
const scan = (re, ownDef) => {
  const live = [], doc = [];
  for (const f of files) {
    if (DEFS.has(f)) continue;
    read(f).split("\n").forEach((line, i) => {
      if (f === "src/app/globals.css" && ownDef.test(line)) return;
      if (!re.test(line)) return;
      (isComment(line) ? doc : live).push(`${f}:${i + 1}`);
    });
  }
  return { live, doc };
};

const rows = [];
for (const t of tokens) {
  const re = new RegExp(`aristo-${t}(?![a-z-])`);
  const own = new RegExp(`^\\s*--aristo-${t}:`);
  const k = camel(t);
  const useKey = keys.includes(k) ? new RegExp(`BRAND_HEX\\.${k}\\b`) : null;
  const a = scan(re, own);
  const b = useKey ? scan(useKey, /^$/) : { live: [], doc: [] };
  rows.push({ t, key: keys.includes(k) ? k : null, live: [...a.live, ...b.live], doc: [...a.doc, ...b.doc] });
}
const dead = rows.filter((r) => r.live.length === 0);
const used = rows.filter((r) => r.live.length > 0);

const tw = (name) => scan(new RegExp(name.replace(/[-]/g, "\-") + "(?![a-z-])"), /^$/);
const utilities = ["aristo-gradient-warm", "aristo-gradient", "shadow-aristo-sm", "shadow-aristo-lg", "shadow-aristo", "text-gradient", "shadow-warm"].map((u) => ({ u, ...tw(u) }));

let md = "# V8.7 dead code (zero references outside the definitions)\n\n";
md += "Generated by `scripts/deadcode.cjs`. A reference is a class (`bg-aristo-x`), a CSS variable (`--aristo-x`) or `BRAND_HEX.x` in `src`, `pages` or `scripts` outside `globals.css`'s own definition line, `tailwind.config.js` and `brandColors.ts` / `.test.ts`; comments are listed apart. `src/app/hx` (local, git-excluded) is not counted.\n\n";
md += `## --aristo-* tokens with no live use (${dead.length} of ${rows.length})\n\n| Token | BRAND_HEX key | Comment-only mentions |\n|---|---|---|\n`;
for (const r of dead) md += `| \`--aristo-${r.t}\` | ${r.key ? "`" + r.key + "`" : "-"} | ${r.doc.length ? r.doc.slice(0, 3).join(", ") : "none"} |\n`;
md += `\n## Tokens still used (${used.length})\n\n| Token | Live uses |\n|---|---|\n`;
for (const r of used) md += `| \`--aristo-${r.t}\` | ${r.live.length}: ${r.live.slice(0, 4).join(", ")}${r.live.length > 4 ? ", ..." : ""} |\n`;
md += "\n## Tailwind utilities and CSS classes\n\n| Name | Live uses | Comment-only |\n|---|---|---|\n";
for (const u of utilities) md += `| \`${u.u}\` | ${u.live.length ? u.live.join(", ") : "none"} | ${u.doc.length ? u.doc.join(", ") : "none"} |\n`;
fs.writeFileSync(path.join(__dirname, "..", "dead-code.md"), md);
console.log("dead tokens:", dead.map((r) => r.t).join(" "));
console.log("used tokens:", used.map((r) => `${r.t}(${r.live.length})`).join(" "));
console.log(utilities.map((u) => `${u.u}: ${u.live.length}`).join("  "));
